/* Generate tools/importer/import-catalog.js: one import script for every non-homepage template,
   driven by the per-page catalog block map. Usage: node tools/importer/scripts/gen-import-catalog.cjs <repoRoot> */
const fs = require('fs');
const path = require('path');

const root = process.argv[2];
const dir = path.join(root, 'tools/importer');
const map = JSON.parse(fs.readFileSync(path.join(dir, 'catalog-block-map.json'), 'utf8'));
const parsers = fs.readdirSync(path.join(dir, 'parsers')).filter((f) => f.endsWith('.js')).map((f) => f.replace('.js', '')).sort();
const transformers = fs.readdirSync(path.join(dir, 'transformers')).filter((f) => f.endsWith('.js')).sort();
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const used = new Set();
Object.values(map.pages).forEach((l) => l.forEach((b) => used.add(b.block)));
const missing = [...used].filter((b) => !parsers.includes(b));
if (missing.length) { console.error('missing parsers', missing); process.exit(1); }

const out = `/* eslint-disable */
/* global WebImporter */
/*
 * Catalog-driven import for every rbcroyalbank.com template except "homepage".
 * Blocks per page come from the site catalog (catalog-block-map.json): each instance is tagged in
 * onLoad (before html2md preprocessing can shift nth-child selectors), then parsed in transform.
 * Generated by gen-import-catalog.cjs — edit that file, not this one.
 */

${parsers.map((p) => `import ${camel(p)}Parser from './parsers/${p}.js';`).join('\n')}

${transformers.map((t) => `import ${camel(t.replace('.js', ''))}Transformer from './transformers/${t}';`).join('\n')}

const BLOCK_MAP = ${JSON.stringify(map.pages)};
const TEMPLATE_OF = ${JSON.stringify(map.templateOf)};

const parsers = {
${parsers.map((p) => `  '${p}': ${camel(p)}Parser,`).join('\n')}
};

const transformers = [${transformers.map((t) => `${camel(t.replace('.js', ''))}Transformer`).join(', ')}];

const BLOCK_ATTR = 'data-catalog-block';
const INDEX_ATTR = 'data-catalog-index';
const VARIANT_ATTR = 'data-catalog-variant';

function normalize(u) {
  try {
    const x = new URL(u);
    return \`https://\${x.host}\${x.pathname}\`;
  } catch (e) { return u; }
}

function instancesFor(url) {
  if (BLOCK_MAP[url]) return BLOCK_MAP[url];
  const n = normalize(url);
  const key = Object.keys(BLOCK_MAP).find((k) => normalize(k) === n || normalize(k).replace(/\\/index\\.html$/, '/') === n.replace(/\\/index\\.html$/, '/'));
  return key ? BLOCK_MAP[key] : [];
}

function templateFor(url) {
  const n = normalize(url);
  const key = Object.keys(TEMPLATE_OF).find((k) => k === url || normalize(k) === n);
  return { name: key ? TEMPLATE_OF[key] : 'catalog', blocks: [], sections: [] };
}

function executeTransformers(hookName, element, payload, template) {
  const enhancedPayload = { ...payload, template };
  transformers.forEach((fn) => {
    try { fn(hookName, element, enhancedPayload); } catch (e) { console.error(\`Transformer failed at \${hookName}:\`, e); }
  });
}

function tagInstances(document, url) {
  instancesFor(url).forEach((inst, i) => {
    let el = null;
    try { el = document.querySelector(inst.selector); } catch (e) { el = null; }
    if (!el || el.hasAttribute(BLOCK_ATTR)) return;
    // never tag an element inside one that is already a block
    if (el.closest(\`[\${BLOCK_ATTR}]\`)) return;
    el.setAttribute(BLOCK_ATTR, inst.block);
    el.setAttribute(INDEX_ATTR, String(i));
    el.setAttribute(VARIANT_ATTR, inst.variant || '');
  });
}

export default {
  onLoad: async ({ document }) => {
    // a redirected page (location is not the catalog URL) is tagged in transform from originalURL
    tagInstances(document, document.defaultView ? document.defaultView.location.href : '');
  },

  transform: (payload) => {
    const { document, url, params } = payload;
    const main = document.body;
    const template = templateFor(params.originalURL || url);

    if (!document.querySelector(\`[\${BLOCK_ATTR}]\`)) tagInstances(document, params.originalURL || url);

    executeTransformers('beforeTransform', main, payload, template);

    const tagged = [...document.querySelectorAll(\`[\${BLOCK_ATTR}]\`)]
      .sort((a, b) => Number(a.getAttribute(INDEX_ATTR)) - Number(b.getAttribute(INDEX_ATTR)));
    const parsed = [];
    tagged.forEach((element) => {
      const name = element.getAttribute(BLOCK_ATTR);
      if (!element.parentNode) return;
      if (!element.textContent.trim() && !element.querySelector('img, picture, iframe, video')) return;
      const parser = parsers[name];
      if (!parser) return;
      try {
        parser(element, { document, url, params });
        parsed.push(name);
      } catch (e) { console.error(\`Failed to parse \${name}:\`, e); }
    });

    executeTransformers('afterTransform', main, payload, template);

    main.appendChild(document.createElement('hr'));
    WebImporter.rules.createMetadata(main, document);
    WebImporter.rules.transformBackgroundImages(main, document);
    WebImporter.rules.adjustImageUrls(main, url, params.originalURL);

    const rawPath = new URL(params.originalURL).pathname
      .replace(/\\/$/, '')
      .replace(/\\.(html?|page|cgi)$/, ''); // EDS paths have no extension (Caribbean pages end in .page)
    const path = WebImporter.FileUtils.sanitizePath(rawPath === '' ? '/index' : rawPath);

    return [{
      element: main,
      path,
      report: { title: document.title, template: template.name, blocks: parsed },
    }];
  },
};
`;
fs.writeFileSync(path.join(dir, 'import-catalog.js'), out);
console.log('wrote import-catalog.js', parsers.length, 'parsers', transformers.length, 'transformers', Object.keys(map.pages).length, 'pages');
